comando = input("Digite o idioma preferencial:")

if comando == "pt":
    print("Olá, mundo!")
elif comando == "en":
    print("Hello, world!")
elif comando == "es":
    print("¡Hola, mundo!")
elif comando == "fr":
    print("Bonjour, monde!")
elif comando == "it":
    print("Ciao, mondo!")
else: 
    print("Idioma não suportado.")
